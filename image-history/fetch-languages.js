// Wikipedia languages for  the language field
"use strict";

const fs = require("fs");
const path = require("path");

const USER_AGENT = "WikiPortraitsTools/1.0 (image-history language list)";
const SITEMATRIX_URL =
  "https://meta.wikimedia.org/w/api.php?action=sitematrix&smtype=language&smsiteprop=code|url&smlangprop=code|name|localname|site&format=json&formatversion=2";
const WIKISTATS_URL =
  "https://wikistats.wmcloud.org/api.php?action=dump&table=wikipedias&format=csv";

const fetchText = async (url) => {
  const response = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
  if (!response.ok) throw new Error(`${url} answered HTTP ${response.status}`);
  return response.text();
};

// Gather subdomains (not always the same as lang code)
// e.g. Alemannic (gsw) vs. als.wikipedia.org
const subdomainOf = (url) =>
  new URL(url).hostname.replace(/\.wikipedia\.org$/, "");

const parseCsvLine = (line) => {
  const fields = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      fields.push(field);
      field = "";
    } else {
      field += ch;
    }
  }
  fields.push(field);
  return fields;
};

const quote = (text) => `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

(async () => {
  const [matrixText, statsText] = await Promise.all([
    fetchText(SITEMATRIX_URL),
    fetchText(WIKISTATS_URL),
  ]);

  const matrix = JSON.parse(matrixText).sitematrix;
  const editions = [];
  for (const key of Object.keys(matrix)) {
    if (!/^\d+$/.test(key)) continue;
    const language = matrix[key];
    const site = (language.site || []).find(
      (candidate) => candidate.code === "wiki",
    );
    if (!site || site.closed) continue;
    const label =
      language.name === language.localname
        ? language.name
        : `${language.name} (${language.localname})`;
    editions.push({ subdomain: subdomainOf(site.url), label });
  }

  const [header, ...rows] = statsText.trim().split("\n").map(parseCsvLine);
  const prefixIndex = header.indexOf("prefix");
  const goodIndex = header.indexOf("good");
  const articles = new Map(
    rows.map((fields) => [fields[prefixIndex], Number(fields[goodIndex]) || 0]),
  );

  editions.sort((a, b) => {
    const sizeDifference =
      (articles.get(b.subdomain) || 0) - (articles.get(a.subdomain) || 0);
    return sizeDifference || a.subdomain.localeCompare(b.subdomain);
  });

  const body = editions
    .map(({ subdomain, label }) => `    [${quote(subdomain)}, ${quote(label)}]`)
    .join(",\n");
  const output = [
    "// Generated by fetch-languages.js from the Wikimedia sitematrix. Run that",
    "// script to refresh; do not edit by hand.",
    "window.WIKIPEDIA_LANGUAGES = [",
    body,
    "];",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(__dirname, "languages.js"), output);
  console.log(`Wrote ${editions.length} Wikipedia editions to languages.js`);
})().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
